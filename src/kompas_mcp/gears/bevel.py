def _polar(radius: float, angle: float) -> list[float]:
    """Planar point [Y, Z] at polar angle counted from +Z toward +Y."""
    return [radius * math.sin(angle), radius * math.cos(angle)]


def _radius(point: list[float]) -> float:
    return math.hypot(float(point[0]), float(point[1]))


def _theta(point: list[float]) -> float:
    """Polar angle of [Y, Z] counted from +Z toward +Y."""
    return math.atan2(float(point[0]), float(point[1]))


def _rotate(point: list[float], angle: float) -> list[float]:
    cosine, sine = math.cos(angle), math.sin(angle)
    return [
        float(point[0]) * cosine + float(point[1]) * sine,
        float(point[1]) * cosine - float(point[0]) * sine,
    ]


def _mirror(point: list[float]) -> list[float]:
    return [-float(point[0]), float(point[1])]


def _dedupe(points: list[list[float]], tolerance: float = 1e-9) -> list[list[float]]:
    unique: list[list[float]] = []
    for point in points:
        candidate = [float(point[0]), float(point[1])]
        if not unique or math.dist(unique[-1], candidate) > tolerance:
            unique.append(candidate)
    return unique


def _signed_area(polygon: list[list[float]]) -> float:
    area = 0.0
    for index in range(len(polygon) - 1):
        x1, y1 = polygon[index]
        x2, y2 = polygon[index + 1]
        area += x1 * y2 - x2 * y1
    return area / 2.0


def _polygon_area(points: list[list[float]]) -> float:
    return abs(_signed_area(points)) if len(points) >= 3 else 0.0


def _involute(value: float) -> float:
    return math.tan(value) - value


