"""Layer 2 nominal geometry for straight bevel gears (no COM).

The module follows ГОСТ 19624-74 macro geometry with the classic Tredgold
construction: the tooth space of the equivalent (virtual) spur gear on the back
cone is projected to the gear apex. The virtual tooth count
``z_v = z / cos delta`` is continuous; only the flank generator is shared with
the cylindrical module, while the conical envelope is built explicitly.

The blank is a dish rather than a cone frustum: a flat base plate with two
conical end faces perpendicular to the tooth (the back cone at the outer end
and the front cone at the inner end) and the face cone between them. The tooth
space is cut between the same two cone planes, so the tooth ends are formed by
those conical faces and never look pointed.

Representation mode is ``nominal``: the flanks are the Tredgold projection of a
sharp-rack generated virtual involute, not an exact spherical involute or an
octoid generated by a real bevel cutter.
"""
