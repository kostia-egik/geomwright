const supportedLocales = new Set(Object.keys(dictionaries));
const storedLocale = localStorage.getItem("geomwright-studio-locale")
  ?? localStorage.getItem("mechanics-ui-locale");
let locale = supportedLocales.has(storedLocale)
  ? storedLocale
  : "ru";

export function getLocale() {
  return locale;
}

export function t(key, fallback = key, variables = {}) {
  const template = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? fallback;
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
}

export function formatNumber(value, maximumFractionDigits = 6) {
  return new Intl.NumberFormat(locale === "ru" ? "ru-RU" : "en-US", {
    maximumFractionDigits,
  }).format(value);
}

const subscriptCharacters = new Map([
  ["₀", "0"], ["₁", "1"], ["₂", "2"], ["₃", "3"], ["₄", "4"],
  ["₅", "5"], ["₆", "6"], ["₇", "7"], ["₈", "8"], ["₉", "9"],
  ["ₐ", "a"], ["ₑ", "e"], ["ₕ", "h"], ["ᵢ", "i"], ["ⱼ", "j"],
  ["ₖ", "k"], ["ₗ", "l"], ["ₘ", "m"], ["ₙ", "n"], ["ₒ", "o"],
  ["ₚ", "p"], ["ᵣ", "r"], ["ₛ", "s"], ["ₜ", "t"], ["ᵤ", "u"],
  ["ᵥ", "v"], ["ₓ", "x"],
]);

export function splitReadableSubscripts(value) {
  const runs = [];
  for (const character of String(value ?? "")) {
    const subscript = subscriptCharacters.has(character);
    const text = subscriptCharacters.get(character) ?? character;
    const previous = runs.at(-1);
    if (previous?.subscript === subscript) previous.text += text;
    else runs.push({ text, subscript });
  }
  return runs;
}

export function applyStaticTranslations(root = document) {
  document.documentElement.lang = locale;
  for (const element of root.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n, element.textContent);
  }
  for (const element of root.querySelectorAll("[data-i18n-title]")) {
    element.title = t(element.dataset.i18nTitle, element.title);
  }
  for (const element of root.querySelectorAll("[data-i18n-label]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nLabel, element.getAttribute("aria-label") || ""));
  }
}

export function setLocale(nextLocale) {
  if (!supportedLocales.has(nextLocale)) return;
  locale = nextLocale;
  localStorage.setItem("geomwright-studio-locale", locale);
  applyStaticTranslations();
  window.dispatchEvent(new CustomEvent("geomwright-language", { detail: { locale } }));
}

export function localizeWarning(item) {
  if (!item) return "";
  if (typeof item === "string") return item;
  return t(`warning.${item.code}`, item.message || item.code || "", item.params || item);
}
